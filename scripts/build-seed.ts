/**
 * Builds server/database/seed/seed.sql from Kim's seed_opportunities.json
 * (51 opps + 48 activities converted from the Excel template, SRS §8).
 *
 *   node scripts/build-seed.ts [path/to/seed_opportunities.json]
 *
 * Applies the SRS 8.1 rules that need the DB:
 *   - customers matched/created by normalised name
 *   - unknown sales owners / creators -> users with is_active = 0 and no password
 *     (Admin activates them and generates a password in the Admin screen)
 *   - countries resolved inside their market
 * Every FK is resolved with a sub-select, so the file is plain portable SQL and
 * re-running it on a fresh DB gives the same result. It is NOT meant to run twice
 * on the same DB (opp_code is unique; the second run fails on the first insert).
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { normalizeCustomerName } from '../shared/normalize.ts'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const src = process.argv[2] ?? path.resolve(root, '../../docs from Kim/seed_opportunities.json')
const out = path.resolve(root, 'server/database/seed/seed.sql')

type SeedOpp = Record<string, any> & { opp_code: string, import_needs_confirm: string[] }
type SeedAct = { opp_code: string, activity_date: string, type: string, content: string, is_customer_facing: boolean, source: string }
const data = JSON.parse(fs.readFileSync(src, 'utf8')) as { source: string, generated: string, opportunities: SeedOpp[], activities: SeedAct[] }

const q = (v: unknown): string => {
  if (v === null || v === undefined || v === '') return 'NULL'
  if (typeof v === 'boolean') return v ? '1' : '0'
  if (typeof v === 'number') return String(v)
  return `'${String(v).replace(/'/g, "''")}'`
}
const now = new Date().toISOString()
const lines: string[] = [
  `-- Generated by scripts/build-seed.ts at ${now}`,
  `-- Source: ${data.source} (generated ${data.generated})`,
]

// ---------- users (SRS 8.1: unknown account -> inactive user)
// created_by holds e-mails (longnn@fpt.com) or plain accounts; the Excel "admin" account is
// renamed so it cannot clash with the real admin created by scripts/create-user.ts.
const accountOf = (v: string) => {
  const acc = v.includes('@') ? v.split('@')[0]! : v
  return acc.toLowerCase() === 'admin' ? 'excel-admin' : acc
}
const users = new Map<string, { account: string, email: string | null, markets: Set<string> }>()
const touchUser = (raw: string | null | undefined, market?: string) => {
  if (!raw) return
  const account = accountOf(raw)
  const key = account.toLowerCase()
  const u = users.get(key) ?? { account, email: null, markets: new Set<string>() }
  if (raw.includes('@') && !u.email) u.email = raw.toLowerCase()
  if (market) u.markets.add(market)
  users.set(key, u)
}
for (const o of data.opportunities) {
  touchUser(o.sales_owner, o.market_code)
  touchUser(o.vi_owner, o.market_code)
  touchUser(o.coordinator, o.market_code)
  touchUser(o.action_owner, o.market_code)
  touchUser(o.created_by)
}
lines.push('', '-- users (inactive until Admin activates them and generates a password)')
for (const u of users.values()) {
  lines.push(`INSERT INTO users (account, email, display_name, role, is_active, password_hash, must_change_password, created_at, updated_at) VALUES (${q(u.account)}, ${q(u.email)}, ${q(u.account)}, 'sales', 0, NULL, 1, ${q(now)}, ${q(now)});`)
}
for (const u of users.values()) {
  for (const m of u.markets) {
    lines.push(`INSERT INTO user_markets (user_id, market_code) SELECT id, ${q(m)} FROM users WHERE lower(account) = lower(${q(u.account)});`)
  }
}

// ---------- customers (dedupe by normalised name)
const customers = new Map<string, { name: string, industry: string | null }>()
for (const o of data.opportunities) {
  const key = normalizeCustomerName(o.customer)
  if (!customers.has(key)) customers.set(key, { name: o.customer, industry: o.industry ?? null })
}
lines.push('', '-- customers')
for (const [key, c] of customers) {
  lines.push(`INSERT INTO customers (name, normalized_name, industry, is_strategic, created_at) VALUES (${q(c.name)}, ${q(key)}, ${q(c.industry)}, 0, ${q(now)});`)
}

// ---------- countries / partners that master data may not have yet
lines.push('', '-- countries & partners referenced by the data (no-op when already present)')
for (const [market, country] of new Set(data.opportunities.map(o => `${o.market_code}|${o.country}`)).values().map(s => s.split('|'))) {
  if (country) lines.push(`INSERT INTO countries (market_code, name) SELECT ${q(market)}, ${q(country)} WHERE NOT EXISTS (SELECT 1 FROM countries WHERE market_code = ${q(market)} AND name = ${q(country)});`)
}
for (const p of new Set(data.opportunities.map(o => o.partner as string))) {
  lines.push(`INSERT INTO partners (name, is_active) SELECT ${q(p)}, 1 WHERE NOT EXISTS (SELECT 1 FROM partners WHERE name = ${q(p)});`)
}

// ---------- opportunities
const userId = (raw: string | null | undefined) =>
  raw ? `(SELECT id FROM users WHERE lower(account) = lower(${q(accountOf(raw))}))` : 'NULL'
lines.push('', '-- opportunities')
let maxSeq = 0
for (const o of data.opportunities) {
  const [, year, seq] = o.opp_code.split('-')
  if (Number(year) === 2026) maxSeq = Math.max(maxSeq, Number(seq))
  // stage/status entry dates are unknown in Excel: use created_at (drives W2 / W7)
  const created = o.created_at ?? o.latest_update_date ?? now.slice(0, 10)
  const cols: Record<string, string> = {
    opp_code: q(o.opp_code),
    name: q(o.name),
    customer_id: `(SELECT id FROM customers WHERE normalized_name = ${q(normalizeCustomerName(o.customer))})`,
    industry: q(o.industry),
    market_code: q(o.market_code),
    country_id: o.country ? `(SELECT id FROM countries WHERE market_code = ${q(o.market_code)} AND name = ${q(o.country)})` : 'NULL',
    partner_id: `(SELECT id FROM partners WHERE name = ${q(o.partner)})`,
    solution: q(o.solution),
    is_laida: q(!!o.is_laida),
    deal_type: q(o.deal_type),
    sales_owner_id: userId(o.sales_owner),
    vi_owner_id: userId(o.vi_owner),
    coordinator_id: userId(o.coordinator),
    amount: q(o.amount ?? 0),
    currency: q(o.currency ?? 'USD'),
    win_rate_override: q(o.win_rate_override),
    priority: q(o.priority),
    status: q(o.status),
    stage: q(o.stage),
    stage_changed_at: q(created),
    status_changed_at: q(created),
    latest_activity: q(o.latest_activity),
    latest_update_date: q(o.latest_update_date),
    last_contact_date: q(o.last_contact_date),
    next_action: q(o.next_action),
    action_owner_id: userId(o.action_owner),
    due_date: q(o.due_date),
    expected_close_date: q(o.expected_close_date),
    pending_reason: q(o.pending_reason),
    lost_reason: q(o.lost_reason),
    blocking_issue: q(o.blocking_issue),
    support_needed: q(o.support_needed),
    background_note: q(o.background_note),
    legacy_ref: q(o.legacy_ref),
    import_needs_confirm: q(o.import_needs_confirm?.length ? JSON.stringify(o.import_needs_confirm) : null),
    created_at: q(`${created}T00:00:00.000Z`),
    created_by: userId(o.created_by),
    updated_at: q(now),
  }
  lines.push(`INSERT INTO opportunities (${Object.keys(cols).join(', ')}) VALUES (${Object.values(cols).join(', ')});`)
}
lines.push(`INSERT INTO opp_code_seq (year, last_no) VALUES (2026, ${maxSeq}) ON CONFLICT (year) DO UPDATE SET last_no = excluded.last_no;`)

// ---------- activities (Remark lines + current activity)
lines.push('', '-- activities')
for (const a of data.activities) {
  lines.push(`INSERT INTO activities (opp_id, activity_date, type, is_customer_facing, content, source, created_at) VALUES ((SELECT id FROM opportunities WHERE opp_code = ${q(a.opp_code)}), ${q(a.activity_date)}, ${q(a.type)}, ${q(!!a.is_customer_facing)}, ${q(a.content)}, ${q(a.source ?? 'import')}, ${q(`${a.activity_date}T00:00:00.000Z`)});`)
}

fs.mkdirSync(path.dirname(out), { recursive: true })
fs.writeFileSync(out, lines.join('\n') + '\n')
console.log(`Wrote ${path.relative(root, out)}: ${users.size} users, ${customers.size} customers, ${data.opportunities.length} opps, ${data.activities.length} activities`)
