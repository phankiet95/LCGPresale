/**
 * LCG Opportunity Management — database schema (SQLite / Cloudflare D1).
 *
 * Ported from Kim's PostgreSQL schema (docs from Kim/schema.sql, SRS v0.1 §4).
 * Portability rules, so the generated SQL migrations can be translated to
 * Azure SQL / PostgreSQL later without redesign:
 *   - Dates           -> TEXT 'YYYY-MM-DD' (JST calendar date, SRS 5.0)
 *   - Timestamps      -> TEXT ISO-8601 UTC, set by the app (no DB-specific default functions)
 *   - Booleans        -> INTEGER 0/1
 *   - Enums           -> TEXT + CHECK constraint
 *   - JSON            -> TEXT
 *   - Money           -> REAL (numeric(15,2) on Postgres / decimal(15,2) on Azure SQL)
 *   - Auto ids        -> INTEGER PRIMARY KEY AUTOINCREMENT (serial / IDENTITY)
 * Computed fields (amount_usd, win_rate, health, warnings…) are NOT stored; they are
 * calculated by shared/rules.ts (SRS §5).
 */
import { sql } from 'drizzle-orm'
import {
  check, index, integer, primaryKey, real, sqliteTable, text, uniqueIndex,
} from 'drizzle-orm/sqlite-core'

export const ROLES = ['admin', 'management', 'market_lead', 'sales', 'viewer'] as const
export const STAGES = ['O', 'D', 'C', 'B', 'A', 'W', 'L'] as const
export const STATUSES = ['Active', 'On Hold', 'Closed'] as const

const nowIso = () => new Date().toISOString()
const createdAt = () => text('created_at').notNull().$defaultFn(nowIso)
const inList = (col: string, values: readonly string[]) =>
  sql.raw(`${col} IN (${values.map(v => `'${v}'`).join(', ')})`)

// ---------------------------------------------------------------- Master data
export const markets = sqliteTable('markets', {
  code: text('code').primaryKey(), // JP, KR, EU, AM, VN, AP, ME
  name: text('name').notNull(),
  sortOrder: integer('sort_order').notNull().default(0),
  isActive: integer('is_active', { mode: 'boolean' }).notNull().default(true),
})

export const countries = sqliteTable('countries', {
  id: integer('id').primaryKey({ autoIncrement: true }),
  marketCode: text('market_code').notNull().references(() => markets.code),
  name: text('name').notNull(),
}, t => [uniqueIndex('ux_countries_market_name').on(t.marketCode, t.name)])

export const users = sqliteTable('users', {
  id: integer('id').primaryKey({ autoIncrement: true }),
  account: text('account').notNull(), // login name, e.g. SonTV16 (case-insensitive unique)
  email: text('email'),
  displayName: text('display_name').notNull(),
  role: text('role', { enum: ROLES }).notNull().default('sales'),
  isActive: integer('is_active', { mode: 'boolean' }).notNull().default(true),
  // Auth (username/password generated by Admin). NULL hash = cannot log in yet.
  passwordHash: text('password_hash'),
  mustChangePassword: integer('must_change_password', { mode: 'boolean' }).notNull().default(true),
  lastLoginAt: text('last_login_at'),
  createdAt: createdAt(),
  updatedAt: text('updated_at').notNull().$defaultFn(nowIso),
}, t => [
  uniqueIndex('ux_users_account').on(sql`lower(${t.account})`),
  uniqueIndex('ux_users_email').on(sql`lower(${t.email})`),
  check('chk_users_role', inList('role', ROLES)),
])

// Market scope of a user (SRS §2). Admin / Management ignore this table (see all).
export const userMarkets = sqliteTable('user_markets', {
  userId: integer('user_id').notNull().references(() => users.id, { onDelete: 'cascade' }),
  marketCode: text('market_code').notNull().references(() => markets.code),
}, t => [primaryKey({ columns: [t.userId, t.marketCode] })])

export const partners = sqliteTable('partners', {
  id: integer('id').primaryKey({ autoIncrement: true }),
  name: text('name').notNull().unique(),
  isActive: integer('is_active', { mode: 'boolean' }).notNull().default(true),
})

// industry | deal_type | activity_type | pending_reason | lost_reason | priority
export const lookups = sqliteTable('lookups', {
  id: integer('id').primaryKey({ autoIncrement: true }),
  category: text('category').notNull(),
  value: text('value').notNull(),
  sortOrder: integer('sort_order').notNull().default(0),
  isActive: integer('is_active', { mode: 'boolean' }).notNull().default(true),
}, t => [uniqueIndex('ux_lookups_cat_value').on(t.category, t.value)])

export const customers = sqliteTable('customers', {
  id: integer('id').primaryKey({ autoIncrement: true }),
  name: text('name').notNull(),
  nameJa: text('name_ja'),
  normalizedName: text('normalized_name').notNull().unique(), // import matching (SRS 8.1)
  industry: text('industry'),
  isStrategic: integer('is_strategic', { mode: 'boolean' }).notNull().default(false),
  createdAt: createdAt(),
})

// SRS 5.2: plan rate per fiscal year
export const fxRates = sqliteTable('fx_rates', {
  fiscalYear: integer('fiscal_year').notNull(),
  currency: text('currency').notNull(),
  rateToUsd: real('rate_to_usd').notNull(),
}, t => [
  primaryKey({ columns: [t.fiscalYear, t.currency] }),
  check('chk_fx_positive', sql`rate_to_usd > 0`),
])

export const settings = sqliteTable('settings', {
  key: text('key').primaryKey(),
  value: text('value').notNull(), // JSON
})

// ---------------------------------------------------------------- Opportunity
export const oppCodeSeq = sqliteTable('opp_code_seq', {
  year: integer('year').primaryKey(),
  lastNo: integer('last_no').notNull(),
})

export const opportunities = sqliteTable('opportunities', {
  id: integer('id').primaryKey({ autoIncrement: true }),
  oppCode: text('opp_code').notNull().unique(), // OPP-2026-001
  name: text('name').notNull(),
  customerId: integer('customer_id').notNull().references(() => customers.id),
  industry: text('industry'),
  marketCode: text('market_code').notNull().references(() => markets.code),
  countryId: integer('country_id').references(() => countries.id),
  partnerId: integer('partner_id').notNull().references(() => partners.id),
  secondaryPartner: text('secondary_partner'),
  solution: text('solution'),
  isLaida: integer('is_laida', { mode: 'boolean' }).notNull().default(false),
  dealType: text('deal_type'), // Project | License | Project+License | AMS
  salesOwnerId: integer('sales_owner_id').notNull().references(() => users.id),
  viOwnerId: integer('vi_owner_id').references(() => users.id), // legacy, no longer edited
  viOwner: text('vi_owner'), // VI name, free text
  biddingLead: text('bidding_lead'), // free text
  coordinatorId: integer('coordinator_id').references(() => users.id),
  amount: real('amount').notNull().default(0),
  currency: text('currency').notNull().default('USD'),
  winRateOverride: integer('win_rate_override'),
  winRateReason: text('win_rate_reason'),
  priority: text('priority'), // High | Medium | Low
  status: text('status', { enum: STATUSES }).notNull().default('Active'),
  stage: text('stage', { enum: STAGES }).notNull().default('O'),
  stageChangedAt: text('stage_changed_at').notNull(), // date, used by W7
  statusChangedAt: text('status_changed_at').notNull(), // date, used by W2
  // Denormalised from the latest activity (SRS 5.9) — updated in the same batch
  latestActivity: text('latest_activity'),
  latestUpdateDate: text('latest_update_date'),
  lastContactDate: text('last_contact_date'),
  nextAction: text('next_action'),
  actionOwnerId: integer('action_owner_id').references(() => users.id),
  dueDate: text('due_date'),
  expectedCloseDate: text('expected_close_date').notNull(),
  closedAt: text('closed_at'),
  pendingReason: text('pending_reason'),
  lostReason: text('lost_reason'),
  blockingIssue: text('blocking_issue'),
  supportNeeded: text('support_needed'),
  backgroundNote: text('background_note'),
  isFocusPinned: integer('is_focus_pinned', { mode: 'boolean' }).notNull().default(false),
  verifiedAt: text('verified_at'),
  verifiedBy: integer('verified_by').references(() => users.id),
  legacyRef: text('legacy_ref'),
  mergedIntoId: integer('merged_into_id'),
  importNeedsConfirm: text('import_needs_confirm'), // JSON array of field names (SRS 8.1)
  createdAt: createdAt(),
  createdBy: integer('created_by').references(() => users.id),
  updatedAt: text('updated_at').notNull().$defaultFn(nowIso),
  deletedAt: text('deleted_at'), // soft delete
}, t => [
  index('ix_opp_market').on(t.marketCode),
  index('ix_opp_partner').on(t.partnerId),
  index('ix_opp_owner').on(t.salesOwnerId),
  index('ix_opp_stage').on(t.stage, t.status),
  index('ix_opp_customer').on(t.customerId),
  check('chk_opp_stage', inList('stage', STAGES)),
  check('chk_opp_status', inList('status', STATUSES)),
  check('chk_opp_amount', sql`amount >= 0`),
  check('chk_opp_win_rate', sql`win_rate_override IS NULL OR (win_rate_override BETWEEN 0 AND 100)`),
  // State machine (SRS 5.8)
  check('chk_closed_consistency', sql`(stage IN ('W','L')) = (status = 'Closed')`),
  check('chk_closed_at', sql`stage NOT IN ('W','L') OR closed_at IS NOT NULL`),
  check('chk_lost_reason', sql`stage <> 'L' OR lost_reason IS NOT NULL`),
  check('chk_won_amount', sql`stage <> 'W' OR amount > 0`),
  check('chk_pending', sql`status <> 'On Hold' OR pending_reason IS NOT NULL`),
])

// ---------------------------------------------------------------- Activity log (replaces Remark)
export const activities = sqliteTable('activities', {
  id: integer('id').primaryKey({ autoIncrement: true }),
  oppId: integer('opp_id').notNull().references(() => opportunities.id, { onDelete: 'cascade' }),
  activityDate: text('activity_date').notNull(), // may be in the future = scheduled event
  type: text('type').notNull(),
  isCustomerFacing: integer('is_customer_facing', { mode: 'boolean' }).notNull().default(false),
  content: text('content').notNull(),
  nextAction: text('next_action'),
  actionOwnerId: integer('action_owner_id').references(() => users.id),
  dueDate: text('due_date'),
  source: text('source').notNull().default('app'), // app | import | system
  createdBy: integer('created_by').references(() => users.id),
  createdAt: createdAt(),
}, t => [index('ix_act_opp_date').on(t.oppId, t.activityDate, t.createdAt)])

// ---------------------------------------------------------------- Action items (replaces Action Tracker)
export const actionItems = sqliteTable('action_items', {
  id: integer('id').primaryKey({ autoIncrement: true }),
  oppId: integer('opp_id').notNull().references(() => opportunities.id, { onDelete: 'cascade' }),
  task: text('task').notNull(),
  ownerId: integer('owner_id').references(() => users.id),
  startDate: text('start_date'),
  dueDate: text('due_date'),
  status: text('status').notNull().default('Open'), // Open | In Progress | Done | Cancelled
  progress: integer('progress'),
  note: text('note'),
  createdAt: createdAt(),
}, t => [
  index('ix_action_items_opp').on(t.oppId),
  check('chk_action_progress', sql`progress IS NULL OR (progress BETWEEN 0 AND 100)`),
])

// ---------------------------------------------------------------- History & snapshot
export const stageHistory = sqliteTable('stage_history', {
  id: integer('id').primaryKey({ autoIncrement: true }),
  oppId: integer('opp_id').notNull().references(() => opportunities.id, { onDelete: 'cascade' }),
  fromStage: text('from_stage'),
  toStage: text('to_stage'),
  fromStatus: text('from_status'),
  toStatus: text('to_status'),
  reason: text('reason'),
  changedBy: integer('changed_by').references(() => users.id),
  changedAt: text('changed_at').notNull().$defaultFn(nowIso),
}, t => [index('ix_stage_history_opp').on(t.oppId)])

// SRS 5.12 — taken every Monday 00:05 JST
export const weeklySnapshots = sqliteTable('weekly_snapshots', {
  weekStart: text('week_start').notNull(), // always a Monday
  oppId: integer('opp_id').notNull().references(() => opportunities.id),
  marketCode: text('market_code').notNull(),
  partnerId: integer('partner_id').notNull(),
  stage: text('stage').notNull(),
  status: text('status').notNull(),
  amountUsd: real('amount_usd').notNull(),
  winRate: integer('win_rate').notNull(),
  weightedUsd: real('weighted_usd').notNull(),
  health: text('health').notNull(),
  expectedCloseDate: text('expected_close_date'),
  warningCodes: text('warning_codes').notNull().default('[]'), // JSON array
}, t => [primaryKey({ columns: [t.weekStart, t.oppId] })])

export const weeklyRecommendations = sqliteTable('weekly_recommendations', {
  id: integer('id').primaryKey({ autoIncrement: true }),
  weekStart: text('week_start').notNull(),
  marketCode: text('market_code').references(() => markets.code), // NULL = all LCG
  finding: text('finding').notNull(),
  impact: text('impact'),
  recommendation: text('recommendation'),
  ownerId: integer('owner_id').references(() => users.id),
  targetDate: text('target_date'),
  createdBy: integer('created_by').references(() => users.id),
  createdAt: createdAt(),
})

export const auditLog = sqliteTable('audit_log', {
  id: integer('id').primaryKey({ autoIncrement: true }),
  entity: text('entity').notNull(),
  entityId: integer('entity_id').notNull(),
  field: text('field'),
  oldValue: text('old_value'),
  newValue: text('new_value'),
  changedBy: integer('changed_by').references(() => users.id),
  changedAt: text('changed_at').notNull().$defaultFn(nowIso),
}, t => [index('ix_audit_entity').on(t.entity, t.entityId)])
